ACCENTS = {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U"}


def render(text, scale=2, color=(255, 255, 255, 255), sx=None):
    from PIL import Image
    text = text.upper()
    w = sum(6 for _ in text) - 1
    img = Image.new("RGBA", ((w + 1) * scale, 8 * scale), (0, 0, 0, 0))
    px = img.load()

    def dot(x, y):
        for yy in range(scale):
            for xx in range(scale):
                px[x * scale + xx, y * scale + yy] = color

    cx = 0
    for ch in text:
        base = ACCENTS.get(ch, ch)
        if ch == "Ñ":
            base = "N"
            for x in (1, 2, 3):
                dot(cx + x, 0)
        g = G.get(base, G[" "])
        if ch in ACCENTS:
            dot(cx + 2, 0)
            dot(cx + 3, 0)
        for j, row in enumerate(g):
            for i, b in enumerate(row):
                if b == "1":
                    dot(cx + i, j + 1)
        cx += 6
    if sx is None:
        sx = 2 if len(text) <= 4 else 1
    if sx != scale:
        img = img.resize((max(1, img.width * sx // scale), img.height), Image.NEAREST)
    return img
